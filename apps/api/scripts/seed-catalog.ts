// Writes the seed catalog (D22) into a new migration (D40): `pnpm --filter @liftwise/api db:seed`.
// Run it after changing packages/core/data/exercises.json; migrations then seed every D1.
// Existing rows are kept, so the user's edits of seed exercises survive.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { seedCatalog } from '@liftwise/core';
import { getTableColumns } from 'drizzle-orm';
import { exercises } from '../src/db/schema.ts';

const local = (path: string) => fileURLToPath(new URL(path, import.meta.url));

// A custom migration keeps drizzle-kit's journal in step with the files wrangler applies.
const drizzleKit = fileURLToPath(new URL('./bin.cjs', import.meta.resolve('drizzle-kit')));
execFileSync(process.execPath, [drizzleKit, 'generate', '--custom', '--name=seed_catalog'], {
  cwd: local('..'),
  stdio: ['ignore', 'ignore', 'inherit'],
});
const journal = JSON.parse(readFileSync(local('../migrations/meta/_journal.json'), 'utf8')) as {
  entries: { tag: string }[];
};
const tag = journal.entries.at(-1)?.tag;
if (!tag?.endsWith('_seed_catalog')) throw new Error(`Unexpected last migration: ${tag}`);

const quote = (value: unknown) =>
  typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
const columns = Object.entries(getTableColumns(exercises));
const names = columns.map(([, column]) => `\`${column.name}\``).join(', ');

// Every row takes the next `seq`, like any server write, so devices pull it.
const bumpSeq =
  'INSERT INTO `sync_counter` (`id`, `value`) VALUES (1, 1) ' +
  'ON CONFLICT (`id`) DO UPDATE SET `value` = `value` + 1;';
const statements = seedCatalog().flatMap((exercise) => {
  const row: Record<string, unknown> = exercise;
  const values = columns.map(([key, column]) => {
    if (key === 'created_at' || key === 'updated_at')
      return "strftime('%Y-%m-%dT%H:%M:%fZ', 'now')";
    if (key === 'seq') return '(SELECT `value` FROM `sync_counter` WHERE `id` = 1)';
    const value = row[key] ?? null;
    return value === null ? 'NULL' : quote(column.mapToDriverValue(value));
  });
  return [
    bumpSeq,
    `INSERT INTO \`exercises\` (${names}) VALUES (${values.join(', ')}) ON CONFLICT (\`id\`) DO NOTHING;`,
  ];
});

writeFileSync(
  local(`../migrations/${tag}.sql`),
  '-- Generated by scripts/seed-catalog.ts from packages/core/data/exercises.json.\n' +
    `${statements.join('--> statement-breakpoint\n')}\n`,
);
console.log(`Seed catalog: ${statements.length / 2} exercises in migrations/${tag}.sql`);
